#!/usr/bin/env bash
# Regenerates docs/performance.md from docs/perf/history.jsonl (one JSON
# line per measurement: op, model, size, triangles, engine, status,
# time_s, peak_rss_mb, peak_above_loaded_mb, machine, commit, date, setup,
# note). Append measurements to the history; never edit the Markdown.
#
# Usage: scripts/perf-report.sh
set -euo pipefail
cd "$(dirname "$0")/.."
python3 - docs/perf/history.jsonl > docs/performance.md <<'PY'
import json, sys
rows = [json.loads(l) for l in open(sys.argv[1]) if l.strip()]
print("# Performance history")
print()
print("Generated by `scripts/perf-report.sh` from `docs/perf/history.jsonl`; append")
print("measurements there and regenerate, never edit this file.")
print()
print("\"Peak RSS\" is the process's peak physical footprint during the operation;")
print("\"above loaded\" is that peak minus the footprint just before it (the")
print("operation's own working memory).")
ops = []
for r in rows:
    if r["op"] not in ops:
        ops.append(r["op"])
for op in ops:
    mine = [r for r in rows if r["op"] == op]
    print()
    print(f"## `{op}`")
    setups = sorted({r.get("setup", "") for r in mine} - {""})
    for s in setups:
        print()
        print(f"Setup: {s}.")
    print()
    print("| size | model | triangles | engine | status | time s | peak RSS MB | above loaded MB | commit | date | machine |")
    print("|---|---|---:|---|---|---:|---:|---:|---|---|---|")
    order = {"1M": 0, "5M": 1, "30M": 2}
    for r in sorted(mine, key=lambda r: (order.get(r["size"], 9), r["triangles"])):
        status = f"**{r['status']}**" if r["status"] == "rejected" else r["status"]
        print(f"| {r['size']} | {r['model']} | {r['triangles']:,} | {r['engine']} | {status} | "
              f"{r['time_s']:.2f} | {r['peak_rss_mb']:,} | {r['peak_above_loaded_mb']:,} | "
              f"`{r['commit']}` | {r['date']} | {r['machine']} |")
    notes = []
    for r in mine:
        n = f"`{r['commit']}` ({r['engine']}, {r['status']}): {r['note']}"
        if r.get("note") and n not in notes:
            notes.append(n)
    if notes:
        print()
        for n in notes:
            print(f"- {n}")
PY
